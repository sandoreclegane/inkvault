def write(path, *objs, mode="w", end="\n"):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, mode, encoding="utf-8", newline="") as f:
        f.write("".join(json.dumps(o) + "\n" for o in objs[:-1]) + (json.dumps(objs[-1]) + end if objs else ""))



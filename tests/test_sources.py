def index_messages():
    from inkvault import index, paths
    assert index.build()
    db = sqlite3.connect(paths.search_db())
    try:
        return db.execute("SELECT id, created, conversation_id, conversation_name, role, text, source FROM messages "
                          "ORDER BY created, id").fetchall()
    finally:
        db.close()



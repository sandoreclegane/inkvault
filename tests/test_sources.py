def test_a_vault_from_the_earlier_format_is_cleaned_once(home):
    from inkvault import export, sources
    image = {"type": "input_image", "image_url": "data:image/png;base64,OLDPIXELS"}
    live = [CODEX_NEW[0], user_item("2026-10-06T09:00:01Z", "look", extra=[image]),
            {"timestamp": "2026-10-06T10:00:00Z", "type": "compacted", "payload": {"message": "so far"}}]
    codex_file(*live)
    db = export.open_vault()  # what the earlier format stored: images kept, compaction skipped, file fully read
    path = os.path.join(os.environ["CODEX_HOME"], "sessions", "2026", "10", "06", "rollout-cx-1.jsonl")
    lines = open(path, "rb").read().splitlines(keepends=True)
    db.execute("INSERT INTO session_lines VALUES ('codex', 'rollout-cx-1.jsonl', ?, ?)",
               (len(lines[0]), lines[1].decode().rstrip("\n")))
    db.execute("INSERT INTO session_files VALUES ('codex', 'rollout-cx-1.jsonl', ?, ?)",
               (os.path.getsize(path), hashlib.sha1(lines[0]).hexdigest()))
    gone = json.dumps(user_item("2026-01-01T00:00:00Z", "deleted", extra=[image]))  # its file no longer exists
    db.execute("INSERT INTO session_lines VALUES ('codex', 'rollout-gone.jsonl', 0, ?)", (gone,))
    db.commit()
    db.close()
    sources.sync()
    stored = "".join(r for (r,) in vault_rows("SELECT raw FROM session_lines"))
    assert "OLDPIXELS" not in stored
    assert "so far" in stored  # read again from the start: the compaction an earlier format skipped
    assert vault_rows("SELECT value FROM meta WHERE key='session_lines_format'") == [(sources.FORMAT,)]
    assert len(vault_rows("SELECT * FROM session_lines WHERE file='rollout-gone.jsonl'")) == 1


def test_tags_that_are_not_known_setup_are_the_users(home):
    from inkvault import sources
    codex_file(CODEX_NEW[0], user_item("2026-10-06T09:00:01Z", "<my_context>notes I pasted</my_context>"),
               user_item("2026-10-06T09:00:02Z", "<command-name>/review</command-name>"))
    sources.sync()
    assert [r[5] for r in index_messages()] == ["<my_context>notes I pasted</my_context>",
                                                "<command-name>/review</command-name>"]


def test_a_prompt_repeated_without_a_reply_between_is_kept(home):
    from inkvault import sources
    codex_file(CODEX_NEW[0], user_item("2026-10-06T10:01:00Z", "run the tests"),
               {"timestamp": "2026-10-06T11:01:00Z", "type": "event_msg",
                "payload": {"type": "user_message", "message": "run the tests"}})
    sources.sync()
    assert [r[5] for r in index_messages()] == ["run the tests", "run the tests"]


def compaction_with_image(pixels):
    return {"timestamp": "2026-10-06T10:00:00Z", "type": "compacted", "payload": {
        "message": "so far", "replacement_history": [
            {"type": "message", "role": "user", "content": [
                {"type": "input_text", "text": "see data:image/png;base64,TEXTONLY in the docs"},
                {"type": "input_image", "image_url": f"data:image/png;base64,{pixels}"}]}]}}


def test_images_nested_in_compaction_history_are_not_stored(home):
    from inkvault import sources
    codex_file(CODEX_NEW[0], compaction_with_image("NESTEDPIXELS"))
    sources.sync()
    stored = "".join(r for (r,) in vault_rows("SELECT raw FROM session_lines"))
    assert "NESTEDPIXELS" not in stored
    assert "TEXTONLY" in stored and "so far" in stored  # text that merely mentions a data URL stays


def test_a_format_2_vault_is_cleaned_again(home):
    from inkvault import export, sources
    codex_file(CODEX_NEW[0])
    db = export.open_vault()
    db.execute("INSERT INTO session_lines VALUES ('codex', 'rollout-gone.jsonl', 0, ?)",
               (json.dumps(compaction_with_image("FORMAT2PIXELS")),))
    db.execute("INSERT INTO meta VALUES ('session_lines_format', '2')")
    db.commit()
    db.close()
    sources.sync()
    assert "FORMAT2PIXELS" not in "".join(r for (r,) in vault_rows("SELECT raw FROM session_lines"))
    assert vault_rows("SELECT value FROM meta WHERE key='session_lines_format'") == [(sources.FORMAT,)]


SCHEMA = {"type": "object", "properties": {"configPath": {"type": ["string", "null"]}}}


def meta_with_tools():
    return {"timestamp": "2026-10-06T09:00:00Z", "type": "session_meta",
            "payload": {"id": "cx-1", "timestamp": "2026-10-06T09:00:00Z", "cwd": "C:\\work\\garden",
                        "dynamic_tools": [{"name": "open", "inputSchema": SCHEMA}]}}


def test_a_schema_type_list_survives_and_attachments_still_go(home):
    from inkvault import sources
    codex_file(meta_with_tools(), compaction_with_image("SCHEMAPIXELS"), *CODEX_NEW[1:])
    assert sources.sync()
    stored = [json.loads(r) for (r,) in vault_rows("SELECT raw FROM session_lines ORDER BY offset")]
    assert stored[0]["payload"]["dynamic_tools"][0]["inputSchema"] == SCHEMA
    assert "SCHEMAPIXELS" not in json.dumps(stored)
    assert [r[5] for r in index_messages()] == ["Fix the planner", "Fixed."]


def test_a_format_2_vault_with_a_schema_type_list_upgrades(home):
    from inkvault import export, sources
    codex_file(CODEX_NEW[0])
    db = export.open_vault()
    db.executemany("INSERT INTO session_lines VALUES ('codex', 'rollout-gone.jsonl', ?, ?)",
                   [(0, json.dumps(meta_with_tools())), (1, json.dumps(compaction_with_image("OLDSCHEMAPIXELS")))])
    db.execute("INSERT INTO meta VALUES ('session_lines_format', '2')")
    db.commit()
    db.close()
    assert sources.sync()
    stored = [json.loads(r) for (r,) in vault_rows(
        "SELECT raw FROM session_lines WHERE file='rollout-gone.jsonl' ORDER BY offset")]
    assert stored[0]["payload"]["dynamic_tools"][0]["inputSchema"] == SCHEMA
    assert "OLDSCHEMAPIXELS" not in json.dumps(stored)
    assert vault_rows("SELECT value FROM meta WHERE key='session_lines_format'") == [(sources.FORMAT,)]

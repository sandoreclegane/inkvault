def index_messages():
    from inkvault import index, paths
    assert index.build()
    db = sqlite3.connect(paths.search_db())
    try:
        return db.execute("SELECT id, created, conversation_id, conversation_name, role, text, source FROM messages "
                          "ORDER BY created, id").fetchall()
    finally:
        db.close()


def test_claude_code_session_becomes_a_conversation(home):
    from inkvault import sources
    write(os.path.join(claude_dir(), "sess-1.jsonl"), *SESSION)
    sources.sync()
    rows = index_messages()
    assert [(r[0], r[4], r[5]) for r in rows] == [
        ("claude_code:u1", "USER", "Add retries to the <b>uploader</b>"),
        ("claude_code:a1", "ASSISTANT", "Adding backoff."),
        ("claude_code:a3", "ASSISTANT", "Done: retries with jitter."),
    ]
    assert {r[2] for r in rows} == {"claude_code:sess-1"}
    assert {r[3] for r in rows} == {"Claude Code · harbor: Add retries to the <b>uploader</b>"}
    assert {r[6] for r in rows} == {"claude_code"}



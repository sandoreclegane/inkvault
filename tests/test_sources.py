def vault_rows(sql):
    from inkvault import paths
    db = sqlite3.connect(paths.vault_db())
    try:
        return db.execute(sql).fetchall()
    finally:
        db.close()


def test_sync_keeps_conversation_lines_only(home):
    from inkvault import sources
    write(os.path.join(claude_dir(), "sess-1.jsonl"), *SESSION)
    assert sources.sync()
    kept = [json.loads(r)["uuid"] for (r,) in vault_rows("SELECT raw FROM session_lines ORDER BY offset")]
    assert kept == ["u1", "a1", "u3", "u4", "a2", "a3"]  # no queue, attachment or tool result
    assert "sk-123" not in "".join(r for (r,) in vault_rows("SELECT raw FROM session_lines"))


def test_lines_are_stored_verbatim(home):
    from inkvault import sources
    path = os.path.join(claude_dir(), "sess-1.jsonl")
    line = '{"type":"user",  "uuid":"u1", "message":{"content":"spacing kept"}}\n'
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(line)
    sources.sync()
    assert vault_rows("SELECT raw FROM session_lines") == [(line.rstrip("\n"),)]


def test_sync_reads_only_what_was_added(home):
    from inkvault import sources
    path = os.path.join(claude_dir(), "sess-1.jsonl")
    write(path, *SESSION[:2])
    sources.sync()
    write(path, SESSION[3], mode="a", end="")  # a reply still being written: no newline yet
    sources.sync()
    assert [json.loads(r)["uuid"] for (r,) in vault_rows("SELECT raw FROM session_lines ORDER BY offset")] == ["u1"]
    with open(path, "a", encoding="utf-8") as f:
        f.write("\n")
    write(path, SESSION[-1], mode="a")
    sources.sync()
    sources.sync()  # nothing new: no duplicates
    assert [json.loads(r)["uuid"] for (r,) in vault_rows("SELECT raw FROM session_lines ORDER BY offset")] == \
        ["u1", "a1", "a3"]


